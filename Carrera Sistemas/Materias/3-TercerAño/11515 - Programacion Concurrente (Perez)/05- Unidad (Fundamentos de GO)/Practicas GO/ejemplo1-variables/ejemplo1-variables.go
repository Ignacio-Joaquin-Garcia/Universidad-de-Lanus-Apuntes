package main

import "fmt"

func main() {
	//Declarion Variables
	var nombre string = "Go"
	var edad int = 15
	var pi float64 = 3.14159
	var esVerdad bool = true

	//Imprimir Variables
	fmt.Println("Nombre: ", nombre)
	fmt.Println("Edad: ", edad)
	fmt.Println("Pi: ", pi)
	fmt.Println("esVerdad: ", esVerdad)

	//Declaracion Corta (Operador Morsa)
	apellido := "Lenguaje"
	fmt.Println("Apellido: ", apellido)
}
